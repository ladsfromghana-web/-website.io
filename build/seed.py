#!/usr/bin/env python3
"""Single source of truth for starting content -> data/seed.json (static / local-preview mode) and supabase/seed.sql (production).
Run from the website/ folder:  python3 build/seed.py"""
import json, uuid, os
NS = uuid.UUID("6f1b8f0e-0000-4000-8000-5ea1c0ffee00")
def uid(*k): return str(uuid.uuid5(NS, "/".join(k)))
I = lambda n: "assets/img/" + n

brands = [
 dict(id="lfg", slug="lads-from-ghana", name="Lads From Ghana",
      description="Ghanaian streetwear built for those who own the block. Every stitch, every graphic \u2014 a statement from the streets of Accra to the world.",
      logo_url=I("lfg-logo.jpg"), banner_url=I("lfg-soon-1.jpg"), instagram_url="https://www.instagram.com/lfg_official_25/",
      coming_soon=True, coming_soon_message="The new collection is dropping soon.", visible=True,
      preview_images=[I("lfg-soon-1.jpg"), I("lfg-soon-2.jpg")], sort=1),
 dict(id="her-district", slug="her-district", name="Her District",
      description="Casual streetwear. Own the streets with a new style.",
      logo_url=I("her-district-logo.jpg"), banner_url=I("hd-hero-tank.jpg"), instagram_url="https://www.instagram.com/her.dst/?__pwa=1#",
      coming_soon=False, coming_soon_message="", visible=True, preview_images=[], sort=2),
]
def product(slug, name, imgs, sort):
    pid = uid("product", slug)
    return dict(id=pid, brand_id="her-district", name=name, slug=slug, price=150.00, description="", category="Tops",
                availability="available", published=True, featured=True, stock=None, sizes=[], sort=sort,
                images=[dict(id=uid("pimg", slug, str(i)), url=I(u), position=i) for i, u in enumerate(imgs)])
products = [
 product("her-district-sleeveless-top", "Her District Sleeveless Top", ["hd-sleeveless-1.jpg", "hd-sleeveless-2.jpg", "hd-sleeveless-3.jpg"], 1),
 product("her-district-crop-top", "Her District Crop Top", ["hd-crop-1.jpg", "hd-crop-2.jpg", "hd-crop-3.jpg"], 2),
]
slides = [
 dict(id=uid("slide", "1"), brand_id=None, layout="photo", image_url=I("slide-first.jpg"), headline="Lads From Ghana \u00d7 Her District", subtext="", cta_label="Explore the brands", cta_url="index.html#collections", position=1, visible=True),
 dict(id=uid("slide", "2"), brand_id="lfg", layout="layered", image_url=I("lfg-hero-cap.jpg"), headline="Lads From Ghana", subtext="Dropping soon", cta_label="Explore Collection", cta_url="lads-from-ghana.html", position=2, visible=True),
 dict(id=uid("slide", "3"), brand_id="her-district", layout="layered", image_url=I("hd-hero-tank.jpg"), headline="Her District", subtext="Casual streetwear", cta_label="Shop Her District", cta_url="her-district.html", position=3, visible=True),
]
L = lambda k, f, b, c: dict(id=uid("look", k), image_url=I(f), brand_id=b, caption=c, visible=True)
look = [
 L("lfg01", "lfg-look-01.jpg", "lfg", "Look 01 \u2014 Culture"), L("hd16", "look-16.jpg", "her-district", "Her District \u2014 Casual Streetwear"),
 L("lfg02", "lfg-look-02.jpg", "lfg", "Look 02 \u2014 Black & White"), L("hd17", "look-17.jpg", "her-district", "Her District \u2014 New Style"),
 L("lfg03", "lfg-look-03.jpg", "lfg", "Look 03 \u2014 Brown Logo Tee"), L("lfg13", "look-13.jpg", "lfg", "Lads From Ghana"),
 L("lfg04", "lfg-look-04.png", "lfg", "Look 04 \u2014 Own The Block"), L("lfg14", "look-14.jpg", "lfg", "The Heritage"),
 L("lfg05", "lfg-look-05.jpg", "lfg", "Look 05 \u2014 Green Trucker"), L("lfg15", "look-15.jpg", "lfg", "The Casual Look"),
 L("lfg06", "lfg-look-06.png", "lfg", "Look 06 \u2014 Pink Trucker"), L("lfg07", "lfg-look-07.jpg", "lfg", "Look 07 \u2014 Crop Teal"),
 L("lfg08", "lfg-look-08.jpg", "lfg", "Look 08 \u2014 Culture Beanie"),
]
for i, r in enumerate(look, 1): r["position"] = i
settings = {"announcement_text": "", "announcement_visible": "false", "promo_label": "",
            "collections_eyebrow": "Collections", "collections_title": "Choose a brand", "collections_intro": "",
            "lookbook_title": "Lookbook", "lookbook_intro": "Lads From Ghana and Her District, together in one gallery.",
            "whatsapp_number": "233244126931"}
seed = dict(brands=brands, products=products, slides=slides, lookbook=look, settings=settings)
os.makedirs("data", exist_ok=True); json.dump(seed, open("data/seed.json", "w"), indent=1, ensure_ascii=False)

q = lambda v: "null" if v is None else ("true" if v is True else "false" if v is False else (str(v) if isinstance(v, (int, float)) else "'" + str(v).replace("'", "''") + "'"))
arr = lambda a: "'" + json.dumps(a).replace("'", "''") + "'::jsonb"
out = ["-- Generated by build/seed.py. Run AFTER schema.sql. Safe to re-run (never overwrites existing rows).", ""]
for b in brands:
    out.append(f"insert into brands(id,slug,name,description,logo_url,banner_url,instagram_url,coming_soon,coming_soon_message,visible,preview_images,sort) values ({q(b['id'])},{q(b['slug'])},{q(b['name'])},{q(b['description'])},{q(b['logo_url'])},{q(b['banner_url'])},{q(b['instagram_url'])},{q(b['coming_soon'])},{q(b['coming_soon_message'])},{q(b['visible'])},{arr(b['preview_images'])},{b['sort']}) on conflict (id) do nothing;")
for p in products:
    out.append(f"insert into products(id,brand_id,name,slug,price,description,category,availability,published,featured,stock,sizes,sort) values ({q(p['id'])},{q(p['brand_id'])},{q(p['name'])},{q(p['slug'])},{p['price']},{q(p['description'])},{q(p['category'])},{q(p['availability'])},{q(p['published'])},{q(p['featured'])},{q(p['stock'])},{arr(p['sizes'])},{p['sort']}) on conflict (id) do nothing;")
    for im in p["images"]:
        out.append(f"insert into product_images(id,product_id,url,position) values ({q(im['id'])},{q(p['id'])},{q(im['url'])},{im['position']}) on conflict (id) do nothing;")
for s in slides:
    out.append(f"insert into homepage_slides(id,brand_id,layout,image_url,headline,subtext,cta_label,cta_url,position,visible) values ({q(s['id'])},{q(s['brand_id'])},{q(s['layout'])},{q(s['image_url'])},{q(s['headline'])},{q(s['subtext'])},{q(s['cta_label'])},{q(s['cta_url'])},{s['position']},{q(s['visible'])}) on conflict (id) do nothing;")
for l in look:
    out.append(f"insert into lookbook_images(id,image_url,brand_id,caption,position,visible) values ({q(l['id'])},{q(l['image_url'])},{q(l['brand_id'])},{q(l['caption'])},{l['position']},{q(l['visible'])}) on conflict (id) do nothing;")
for k, v in settings.items():
    out.append(f"insert into site_settings(key,value) values ({q(k)},{q(v)}) on conflict (key) do nothing;")
open("supabase/seed.sql", "w").write("\n".join(out) + "\n")
print("seed ok:", len(brands), "brands,", len(products), "products,", len(slides), "slides,", len(look), "lookbook")
